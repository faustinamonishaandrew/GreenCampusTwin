// Helper to generate 365 days of historical data deterministically
export function generate365DaysData(): TelemetryDataPoint[] {
  const data: TelemetryDataPoint[] = [];
  const today = new Date();
  
  for (let i = 364; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    const dayOfYear = 365 - i;
    const seasonFactor = 1 + 0.25 * Math.sin((dayOfYear / 365) * 2 * Math.PI - Math.PI / 2); // Higher in summer
    const isWeekend = d.getDay() === 0 || d.getDay() === 6;
    const weekendMultiplier = isWeekend ? 0.45 : 1.0;

    SAMPLE_BUILDINGS.forEach((bldg) => {
      // Base usage per sq ft
      const baseEnergy = (bldg.areaSqFt / 100) * 0.9 * seasonFactor * weekendMultiplier;
      const baseWater = (bldg.occupancyCapacity * 8) * seasonFactor * weekendMultiplier;
      const baseWaste = (bldg.occupancyCapacity * 0.12) * weekendMultiplier;
      
      // Add pseudo-random variations
      const noiseEnergy = 1 + (Math.sin(dayOfYear * 13 + parseInt(bldg.code.slice(-2) || '1')) * 0.12);
      const noiseWater = 1 + (Math.cos(dayOfYear * 7 + parseInt(bldg.code.slice(-2) || '1')) * 0.15);
      
      // Check for forced anomaly spikes on specific days for rich anomaly detection testing
      const isEnergySpike = (i === 3 || i === 12) && (bldg.id === 'bldg-3' || bldg.id === 'bldg-2');
      const isWaterLeak = (i === 1 || i === 8) && (bldg.id === 'bldg-5' || bldg.id === 'bldg-3');

      const energyKwh = Math.round((baseEnergy * noiseEnergy) * (isEnergySpike ? 2.4 : 1));
      const waterLiters = Math.round((baseWater * noiseWater) * (isWaterLeak ? 3.1 : 1));
      const wasteKg = Math.round(baseWaste * (1 + Math.sin(dayOfYear) * 0.1));
      const solarGen = Math.round(bldg.solarCapacityKw * 4.8 * (0.8 + 0.4 * Math.sin(dayOfYear * 0.017)));
      const carbonKg = Math.round(energyKwh * 0.72 - solarGen * 0.5); // Grid intensity factor
      const aqi = Math.round(30 + Math.sin(dayOfYear * 0.05) * 15 + (bldg.category === 'lab' ? 12 : 0));
      const tempC = Number((22 + Math.sin((dayOfYear / 365) * 2 * Math.PI) * 7 + (isEnergySpike ? 3.5 : 0)).toFixed(1));

      data.push({
        timestamp: dateStr,
        buildingId: bldg.id,
        energyKwh: Math.max(50, energyKwh),
        waterLiters: Math.max(100, waterLiters),
        wasteKg: Math.max(10, wasteKg),
        aqi: Math.min(200, Math.max(15, aqi)),
        temperatureC: tempC,
        humidityPct: Math.round(55 + Math.cos(dayOfYear * 0.1) * 15),
        solarGenerationKwh: solarGen,
        carbonKg: Math.max(0, carbonKg),
        occupancyPct: Math.round((isWeekend ? 20 : 82) + Math.sin(dayOfYear * 0.2) * 10),
        isAnomaly: isEnergySpike || isWaterLeak,
      });
    });
  }
  return data;
}

